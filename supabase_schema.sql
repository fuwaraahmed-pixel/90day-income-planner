    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    week_title TEXT NOT NULL,
    outreach_count INT DEFAULT 0,
    replies_count INT DEFAULT 0,
    interested_count INT DEFAULT 0,
    clients_won_count INT DEFAULT 0,
    new_income NUMERIC DEFAULT 0,
    main_achievement TEXT DEFAULT '',
    main_problem TEXT DEFAULT '',
    next_week_priority TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. SERVICES TABLE
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    title TEXT NOT NULL,
    price TEXT NOT NULL,
    delivery_time TEXT DEFAULT '',
    includes TEXT[] DEFAULT '{}',
    notes TEXT DEFAULT '',
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. NINETY DAY PLAN TABLE
CREATE TABLE IF NOT EXISTS public.ninety_day_plan (
    id TEXT NOT NULL,
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    month_title TEXT NOT NULL,
    target_income TEXT DEFAULT '',
    new_income_target TEXT DEFAULT '',
    focus TEXT DEFAULT '',
    weeks JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
