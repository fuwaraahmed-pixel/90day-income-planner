-- 1. ENABLE EXTENSION
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. SETTINGS TABLE
CREATE TABLE IF NOT EXISTS public.settings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    target_income NUMERIC NOT NULL DEFAULT 100000,
    installment NUMERIC NOT NULL DEFAULT 80000,
    daily_outreach_target INT NOT NULL DEFAULT 10,
    currency TEXT NOT NULL DEFAULT '৳',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_user_settings UNIQUE(user_id)
);

-- 3. TASKS TABLE
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Sales',
    priority TEXT NOT NULL DEFAULT 'High',
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    target_metric TEXT DEFAULT '',
    status TEXT NOT NULL DEFAULT 'NotStarted',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. CRM CLIENTS (LEADS) TABLE
CREATE TABLE IF NOT EXISTS public.crm_clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    client_name TEXT NOT NULL,
    business_name TEXT NOT NULL,
    contact TEXT DEFAULT '',
    service TEXT DEFAULT '',
    quoted_price NUMERIC DEFAULT 0,
    advance NUMERIC DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'New',
    next_follow_up DATE NULL,
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. INCOME TABLE
CREATE TABLE IF NOT EXISTS public.income (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) DEFAULT auth.uid(),
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    source TEXT NOT NULL,
    client_details TEXT NOT NULL,
    amount NUMERIC NOT NULL DEFAULT 0,
