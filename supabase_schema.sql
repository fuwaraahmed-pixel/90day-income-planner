-- ====================================================================
-- ATOMIC POSTGRESQL RPC FOR TUITION PAYMENT & INCOME CREATION
-- ====================================================================
CREATE OR REPLACE FUNCTION public.record_tuition_payment(
    p_student_id BIGINT,
    p_payment_date DATE,
    p_payment_month TEXT,
    p_amount NUMERIC,
    p_payment_method TEXT DEFAULT 'Cash',
    p_note TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_student_name TEXT;
    v_class_name TEXT;
    v_client_details TEXT;
    v_income_id BIGINT;
    v_payment_id BIGINT;
    v_result JSONB;
BEGIN
    -- 1. Verify user authentication
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;

    -- 2. Validate input values
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than zero';
    END IF;

    IF p_payment_month IS NULL OR p_payment_month !~ '^\d{4}-(0[1-9]|1[0-2])$' THEN
        RAISE EXCEPTION 'Invalid payment month format. Must be YYYY-MM (e.g. 2026-09)';
    END IF;

    -- 3. Verify student ownership and fetch student details
    SELECT student_name, class_name
    INTO v_student_name, v_class_name
    FROM public.tuition_students
    WHERE id = p_student_id AND user_id = v_user_id;

    IF v_student_name IS NULL THEN
        RAISE EXCEPTION 'Student not found or access denied';
    END IF;

    -- Format client_details cleanly without trailing hyphen when class_name is empty
    IF v_class_name IS NOT NULL AND length(trim(v_class_name)) > 0 THEN
        v_client_details := v_student_name || ' - ' || trim(v_class_name);
    ELSE
        v_client_details := v_student_name;
    END IF;

    -- 4. Check duplicate monthly payment
    IF EXISTS (
        SELECT 1 FROM public.tuition_payments
        WHERE user_id = v_user_id
          AND student_id = p_student_id
          AND payment_month = p_payment_month
    ) THEN
        RAISE EXCEPTION 'A payment for month % already exists for this student', p_payment_month;
    END IF;

    -- 5. Create Income record
    INSERT INTO public.income (
        user_id,
        date,
        source,
        client_details,
        amount,
        payment_type,
        month,
        notes
    ) VALUES (
        v_user_id,
        p_payment_date,
        'Tuition',
        v_client_details,
        p_amount,
        p_payment_method,
        p_payment_month,
        COALESCE(p_note, '')
    )
    RETURNING id INTO v_income_id;

    -- 6. Create Tuition Payment record linked to Income
    INSERT INTO public.tuition_payments (
        user_id,
        student_id,
        payment_date,
        payment_month,
        amount,
        payment_method,
        note,
        income_id
    ) VALUES (
        v_user_id,
        p_student_id,
        p_payment_date,
        p_payment_month,
        p_amount,
        p_payment_method,
        COALESCE(p_note, ''),
        v_income_id
    )
    RETURNING id INTO v_payment_id;

    -- 7. Build and return combined result JSON
    SELECT jsonb_build_object(
        'success', true,
        'payment_id', v_payment_id,
        'income_id', v_income_id,
        'student_id', p_student_id,
        'amount', p_amount,
        'payment_month', p_payment_month,
        'payment_date', p_payment_date,
        'payment_method', p_payment_method,
        'note', p_note
    ) INTO v_result;

    RETURN v_result;
END;
$$;

