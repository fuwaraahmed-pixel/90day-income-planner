-- ATOMIC POSTGRESQL RPC FOR RECORDING CUSTOMER DUE PAYMENT & INCOME CREATION
CREATE OR REPLACE FUNCTION public.record_customer_due_payment(
    p_payment_id UUID,
    p_due_id BIGINT,
    p_payment_date DATE,
    p_amount NUMERIC,
    p_payment_method TEXT DEFAULT 'bKash',
    p_note TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_customer_id BIGINT;
    v_customer_name TEXT;
    v_description TEXT;
    v_total_amount NUMERIC;
    v_current_paid NUMERIC;
    v_new_paid NUMERIC;
    v_new_due NUMERIC;
    v_new_status TEXT;
    v_client_details TEXT;
    v_income_id BIGINT;
    v_existing_payment RECORD;
    v_result JSONB;
BEGIN
    -- 1. Authentication check
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;

    -- 2. Validate input parameters
    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION 'Payment amount must be greater than zero';
    END IF;

    IF p_payment_id IS NULL THEN
        RAISE EXCEPTION 'Payment ID is required for idempotency tracking';
    END IF;

    -- 3. Retrieve due record
    SELECT customer_id, customer_name, description, total_amount, paid_amount
    INTO v_customer_id, v_customer_name, v_description, v_total_amount, v_current_paid
    FROM public.customer_dues
    WHERE id = p_due_id AND user_id = v_user_id;

    IF v_customer_name IS NULL THEN
        RAISE EXCEPTION 'Due record not found or access denied';
    END IF;

    -- 4. Check for duplicate payment (Idempotency)
    SELECT * INTO v_existing_payment
    FROM public.customer_due_payments
    WHERE id = p_payment_id AND user_id = v_user_id;

    IF v_existing_payment IS NOT NULL THEN
        RETURN jsonb_build_object(
            'success', true,
            'idempotent_retry', true,
            'payment_id', v_existing_payment.id,
            'message', 'Payment already recorded previously. Duplicate request safely skipped.'
        );
    END IF;

    -- 5. Calculate new balances
    v_new_paid := v_current_paid + p_amount;
    v_new_due := GREATEST(0, v_total_amount - v_new_paid);

    IF v_new_due = 0 THEN
        v_new_status := 'Paid';
    ELSE
        v_new_status := 'Partially Paid';
    END IF;

    -- 6. Format client details for Income record
    v_client_details := v_customer_name || ' (' || v_description || ')';

    -- 7. Insert Income record linked to this payment
    INSERT INTO public.income (
        user_id,
        date,
        source,
        client_details,
        amount,
        payment_type,
        month,
        notes
    ) VALUES (
        v_user_id,
        p_payment_date,
        'Customer Payment',
        v_client_details,
        p_amount,
        p_payment_method,
        'Month 1',
        COALESCE(p_note, '')
    )
    RETURNING id INTO v_income_id;

    -- 8. Insert Due Payment record
    INSERT INTO public.customer_due_payments (
        id,
        user_id,
        due_id,
        customer_id,
        amount,
        payment_date,
        payment_method,
        note,
        income_id
    ) VALUES (
        p_payment_id,
        v_user_id,
        p_due_id,
        v_customer_id,
        p_amount,
        p_payment_date,
        p_payment_method,
        COALESCE(p_note, ''),
        v_income_id
    );

    -- 9. Update Customer Dues summary
    UPDATE public.customer_dues
    SET paid_amount = v_new_paid,
        due_amount = v_new_due,
        status = v_new_status,
        updated_at = NOW()
    WHERE id = p_due_id AND user_id = v_user_id;

    -- 10. Build result object
    SELECT jsonb_build_object(
        'success', true,
        'payment_id', p_payment_id,
        'income_id', v_income_id,
        'due_id', p_due_id,
        'amount', p_amount,
        'new_paid', v_new_paid,
        'new_due', v_new_due,
        'status', v_new_status
    ) INTO v_result;

    RETURN v_result;
END;
$$;

