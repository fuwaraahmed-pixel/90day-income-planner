-- 1. FUNCTION TO APPROVE PAYMENT REQUEST
CREATE OR REPLACE FUNCTION public.approve_payment_request(request_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    req RECORD;
    caller_email TEXT;
BEGIN
    caller_email := auth.jwt() ->> 'email';
    
    IF caller_email IS NULL OR caller_email != 'fuwaraahmed@gmail.com' THEN
        RAISE EXCEPTION 'Unauthorized: Only the system administrator can approve payment requests.';
    END IF;

    SELECT * INTO req FROM public.payment_requests WHERE id = request_id AND status = 'pending';
    
    IF req IS NULL THEN
        RAISE EXCEPTION 'Payment request not found or already processed.';
    END IF;

    UPDATE public.payment_requests 
    SET status = 'approved', updated_at = NOW() 
    WHERE id = request_id;

    INSERT INTO public.subscriptions (user_id, user_email, status, plan_name, starts_at, expires_at, updated_at)
    VALUES (req.user_id, req.user_email, 'active', req.plan_name, NOW(), NOW() + INTERVAL '30 days', NOW())
    ON CONFLICT (user_id) 
    DO UPDATE SET 
        status = 'active',
        plan_name = EXCLUDED.plan_name,
        starts_at = NOW(),
        expires_at = NOW() + INTERVAL '30 days',
        updated_at = NOW();

    RETURN jsonb_build_object('success', true, 'message', 'Payment request approved successfully.');
END;
$$;

-- 2. FUNCTION TO REJECT PAYMENT REQUEST
CREATE OR REPLACE FUNCTION public.reject_payment_request(request_id UUID, rejection_reason TEXT DEFAULT '')
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    req RECORD;
    caller_email TEXT;
BEGIN
    caller_email := auth.jwt() ->> 'email';
    
    IF caller_email IS NULL OR caller_email != 'fuwaraahmed@gmail.com' THEN
        RAISE EXCEPTION 'Unauthorized: Only the system administrator can reject payment requests.';
    END IF;

    SELECT * INTO req FROM public.payment_requests WHERE id = request_id AND status = 'pending';
    
    IF req IS NULL THEN
        RAISE EXCEPTION 'Payment request not found or already processed.';
    END IF;

    UPDATE public.payment_requests 
    SET status = 'rejected', admin_notes = rejection_reason, updated_at = NOW() 
    WHERE id = request_id;

    UPDATE public.subscriptions 
    SET status = 'rejected', updated_at = NOW() 
    WHERE user_id = req.user_id AND status != 'active';

    RETURN jsonb_build_object('success', true, 'message', 'Payment request rejected.');
END;
$$;

